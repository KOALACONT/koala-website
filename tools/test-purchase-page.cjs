const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'dist/buy-20ft-container/index.html'), 'utf8');
const test = fs.readFileSync(path.join(root, 'preview-purchase/buy-20ft-container/index.html'), 'utf8');
assert.equal((html.match(/<form\b/g) || []).length, 1);
assert.match(html, /name="intent" value="buy"/);
assert.match(html, /name="size" value="20ft"/);
assert.match(html, /name="config" value="gp"/);
assert.match(html, /name="phone"[^>]*required/);
assert.match(html, /name="suburb"[^>]*required/);
assert.match(html, /name="grade"/);
assert.match(html, /name="written" value="yes"/);
assert.match(html, /name="business_url"/);
assert.match(html, /data-quote method="post"/);
assert.doesNotMatch(html, /value="hire"|value="40ft"|container-modifications|shipping-container-hire/);
assert.match(html, /allow_enhanced_conversions:false/);
assert.match(html, /AW-10966856204/);
assert.doesNotMatch(test, /googletagmanager.com|AW-10966856204/);
assert.match(test, /"ads":null/);
assert.match(html, /canonical" href="https:\/\/koalacontainers.com.au\/buy-20ft-container\//);
assert.ok(html.indexOf('<form') < html.indexOf('Choose the condition that suits'));
const config = JSON.parse(html.match(/<script id="site-config" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.equal(config.brand, 'KOA');
assert.ok(config.endpoint);
console.log('PASS: purchase defaults, required contact fields, grade/written quote, honeypot, shared handler/config, form placement, focused links, production tracking and staging suppression');
